import 'dart:io';

/// Compile a deliberately small, documented CSS custom-property vocabulary.
/// No network, browser, package download, or runtime CSS engine is required.
Map<String, String> parseStyleVariables(String css) {
  final source = css.replaceAll(RegExp(r'/\*[\s\S]*?\*/'), '');
  final blocks = <String, Map<String, String>>{};
  final blockPattern = RegExp(r'([^{}]+)\{([^{}]*)\}');
  for (final match in blockPattern.allMatches(source)) {
    final selector = match[1]!.trim();
    final mode = switch (selector) {
      ':root' => 'root',
      '[data-theme="light"]' => 'light',
      '[data-theme="dark"]' => 'dark',
      _ => throw FormatException('Unsupported style selector: $selector'),
    };
    if (blocks.containsKey(mode)) {
      throw FormatException('Duplicate $mode block');
    }
    final values = <String, String>{};
    for (final declaration in match[2]!.split(';')) {
      if (declaration.trim().isEmpty) continue;
      final property = RegExp(
        r'^\s*--([a-z][a-z0-9-]*)\s*:\s*(.+?)\s*$',
      ).firstMatch(declaration);
      if (property == null) {
        throw FormatException('Invalid CSS variable: $declaration');
      }
      final key = property[1]!;
      if (values.containsKey(key)) {
        throw FormatException('Duplicate --$key in $mode');
      }
      values[key] = property[2]!;
    }
    blocks[mode] = values;
  }
  if (source.replaceAll(blockPattern, '').trim().isNotEmpty ||
      !['root', 'light', 'dark'].every(blocks.containsKey)) {
    throw const FormatException(
      'Expected :root, light and dark CSS variable blocks',
    );
  }
  String resolve(String mode, String key, Set<String> visited) {
    final id = '$mode.$key';
    if (!visited.add(id)) throw FormatException('Circular CSS variable: $id');
    final value = blocks[mode]?[key] ?? blocks['root']?[key];
    if (value == null) throw FormatException('Missing CSS variable: $id');
    final reference = RegExp(r'^var\(--([a-z][a-z0-9-]*)\)$').firstMatch(value);
    if (reference != null) return resolve(mode, reference[1]!, visited);
    return value;
  }

  final result = <String, String>{};
  for (final block in blocks.entries) {
    for (final key in block.value.keys) {
      final value = resolve(block.key, key, {});
      final id = '${block.key}.$key';
      if (block.key != 'root' || key.startsWith('color-')) {
        if (!RegExp(r'^#[0-9a-fA-F]{6}$').hasMatch(value)) {
          throw FormatException('$id requires a #RRGGBB color');
        }
        result[id] = 'FF${value.substring(1).toUpperCase()}';
      } else if (key == 'font-family') {
        final font = RegExp(
          r'''^(['"])([a-zA-Z0-9 _-]+)\1$''',
        ).firstMatch(value);
        if (font == null) {
          throw const FormatException(
            'font-family requires one quoted font name',
          );
        }
        result[id] = "'${font[2]}'";
      } else {
        final size = RegExp(r'^([0-9]+(?:\.[0-9]+)?)px$').firstMatch(value);
        final number = size == null ? null : double.tryParse(size[1]!);
        if (number == null || number <= 0 || number > 1000) {
          throw FormatException(
            '$id requires a size from 0 to 1000px, excluding zero',
          );
        }
        result[id] = number.toString();
      }
    }
  }
  return result;
}

Map<String, String> compileStyles(String css, Map<String, String> templates) {
  final values = parseStyleVariables(css);
  final used = <String>{};
  final outputs = <String, String>{};
  for (final template in templates.entries) {
    outputs[template.key] =
        '// GENERATED from styles/app.css. Do not edit this file.\n'
        '// Run: dart run tool/generate_styles.dart\n'
        '${template.value.replaceAllMapped(RegExp(r'\{\{([a-z0-9.-]+)\}\}'), (match) {
          final key = match[1]!;
          used.add(key);
          return values[key] ?? (throw FormatException('Missing CSS style: $key'));
        })}';
  }
  final unused = values.keys.where((key) => !used.contains(key));
  if (unused.isNotEmpty) {
    throw FormatException('Unused CSS styles: ${unused.join(', ')}');
  }
  return outputs.map(
    (name, source) => MapEntry(name, '${source.trimRight()}\n'),
  );
}

void main(List<String> args) {
  try {
    if (args.any((arg) => arg != '--check')) {
      throw const FormatException(
        'Usage: dart run tool/generate_styles.dart [--check]',
      );
    }
    final root = Directory.fromUri(Platform.script.resolve('../'));
    final templates = <String, String>{};
    for (final name in ['app_palette.dart', 'style_tokens.dart']) {
      templates[name] = File(
        '${root.path}/tool/style_templates/$name.template',
      ).readAsStringSync();
    }
    final generated = compileStyles(
      File('${root.path}/styles/app.css').readAsStringSync(),
      templates,
    );
    final stale = <String>[];
    for (final output in generated.entries) {
      final file = File('${root.path}/lib/app/${output.key}');
      if (args.contains('--check')) {
        if (!file.existsSync() ||
            file.readAsStringSync().replaceAll('\r\n', '\n') !=
                output.value.replaceAll('\r\n', '\n')) {
          stale.add(output.key);
        }
      } else {
        file.writeAsStringSync(output.value);
      }
    }
    if (stale.isNotEmpty) {
      throw StateError(
        'CSS outputs out of date: ${stale.join(', ')}. Run dart run tool/generate_styles.dart',
      );
    }
    stdout.writeln(
      args.contains('--check')
          ? 'CSS outputs are up to date.'
          : 'Generated Flutter styles from styles/app.css.',
    );
  } catch (error) {
    stderr.writeln(error);
    exitCode = 1;
  }
}
